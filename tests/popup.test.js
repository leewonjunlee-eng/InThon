import test from "node:test";
import assert from "node:assert/strict";
import { DEFAULT_SETTINGS, emptySlot } from "../extension/lib/logic.js";

test("the real popup editor keeps unsaved edits during updates and submits enabled conditions", async () => {
  const handlers = new Map(), sent = [], savedSelections = [];
  let modalOpened = 0, onCancel;
  const dialog = { showModal() { modalOpened++; }, addEventListener(_, callback) { onCancel = callback; } };
  const main = { innerHTML: "", querySelectorAll: () => [], querySelector: selector => selector === ".delete-dialog" && main.innerHTML.includes("<dialog") ? dialog : null };
  const toggle = { dataset: {}, textContent: "" };
  const root = { addEventListener: (event, handler) => handlers.set(event, handler) };
  const slot = { ...emptySlot(), tabId: 11, title: "제품 공개", host: "example.com", role: "standby", profileId: "auto",
    alertSetup: { status: "ready", source: "title", profile: { name: "판매 알림", summaryFocus: "가격", keywordExamples: ["가격", "한타"], rules: [{ text: "가격이 공개되면", enabled: true }] } } };
  const state = { slots: [slot, emptySlot()], profiles: [{ id: "lol", name: "롤" }, { id: "custom-game", name: "내 경기" }], settings: DEFAULT_SETTINGS, view: { tabId: 11 }, status: "", available: [{ id: 11, title: "제품 공개" }, { id: 12, title: "다른 탭" }], manual: null, peek: null };
  let subscriber;
  const documentBefore = globalThis.document, chromeBefore = globalThis.chrome;
  globalThis.document = { documentElement: { classList: { add() {} } }, activeElement: null,
    getElementById: id => id === "ab-mock" ? root : id === "settings-toggle" ? toggle : main };
  globalThis.chrome = { runtime: { id: "test", onMessage: { addListener: handler => { subscriber = handler; } },
    sendMessage: async message => { sent.push(message); if (message.cmd === "state") subscriber({ to: "ui", state }); return { ok: true }; } },
    storage: { session: { get: async () => ({ uiSelections: [null, { id: 12, title: "다른 탭" }] }), set: async value => { savedSelections.push(structuredClone(value.uiSelections)); } } } };
  const click = async action => {
    handlers.get("click")({ target: { closest: () => ({ dataset: { action }, disabled: false }) } });
    await new Promise(resolve => setImmediate(resolve));
  };
  try {
    await import("../extension/popup/app.js");
    await new Promise(resolve => setImmediate(resolve));
    assert(main.innerHTML.includes('aria-label="1번 탭 알림 프리셋"'));
    assert(main.innerHTML.includes('value="custom-game"'));
    assert(!main.innerHTML.includes('value="lol"'));
    assert(!main.innerHTML.includes('개 조건 사용 중'));
    assert(main.innerHTML.includes('aria-label="1번 탭 삭제"'));
    await click('add-slot');
    assert(!main.innerHTML.includes('연결할 탭 선택'));
    await click('pick:1');
    assert(!main.innerHTML.includes('선택만으로 소리가'));
    await click('back');
    handlers.get('change')({ target: { dataset: { profile: '0' }, value: 'custom-game' } });
    await new Promise(resolve => setImmediate(resolve));
    assert(sent.some(message => message.cmd === 'set-profile' && message.index === 0 && message.profileId === 'custom-game'));
    assert(main.innerHTML.includes("알림 조건 확인·수정"));
    globalThis.document.activeElement = { tagName: 'SELECT', dataset: { profile: '0' } };
    const publishProfile = (profileId, setup = slot.alertSetup) => subscriber({ to: 'ui', state: { ...structuredClone(state), slots: [{ ...structuredClone(slot), profileId, alertSetup: structuredClone(setup) }, emptySlot()] } });
    publishProfile('');
    assert(!main.innerHTML.includes('알림 조건 확인·수정'), 'off hides the summary while the dropdown remains focused');
    publishProfile('auto', { status: 'generating', phase: 'scanning' });
    assert(main.innerHTML.includes('알림 조건 확인·수정'), 'auto immediately restores the summary');
    assert(main.innerHTML.includes('읽는 중'));
    publishProfile('auto');
    assert(main.innerHTML.includes('판매 알림'), 'generation result updates without blurring the dropdown');
    publishProfile('custom-game');
    assert(!main.innerHTML.includes('알림 조건 확인·수정'), 'custom presets do not show the automatic condition card');
    publishProfile('auto');
    globalThis.document.activeElement = null;

    assert(!main.innerHTML.includes("인식 확인"));
    await click("edit-alert:0");
    assert(main.innerHTML.includes("가격이 공개되면"));
    assert(main.innerHTML.startsWith('<div class="settings-top">'));
    assert(!main.innerHTML.includes("← 돌아가기"));
    assert(!main.innerHTML.includes('data-alert-field="summaryFocus"'));
    assert(main.innerHTML.includes('data-alert-field="keywords"'));
    assert(main.innerHTML.includes('placeholder="예: 가격"'));
    assert(main.innerHTML.includes('키워드 설정'));
    assert(!main.innerHTML.includes('바로 알림 키워드'));
    assert(main.innerHTML.includes('키워드는 직접 입력하고 쉼표 로 구분하세요. 자주 나오는 단어는 알림이 많아질 수 있어요.'));
    handlers.get("input")({ target: { dataset: { alertField: "condition" }, value: "판매가 시작되면" } });
    handlers.get("input")({ target: { dataset: { alertField: "keywords" }, value: "판매 시작, 오픈" } });
    subscriber({ to: "ui", state: structuredClone(state) });
    assert(main.innerHTML.includes("판매가 시작되면"), "incoming state cannot erase unsaved changes");
    await click("save-alert");
    const save = sent.find(message => message.cmd === "save-alerts");
    assert.equal(save.tabId, 11);
    assert.deepEqual(save.profile.rules, [{ text: "판매가 시작되면", enabled: true }]);
    assert.deepEqual(save.profile.keywords, ["판매 시작", "오픈"]);
    assert.deepEqual(save.profile.watchPhrases, []);
    assert.equal(save.profile.keywordMode, "direct");
    assert(main.innerHTML.includes("알림 조건을 저장했어요."));
    await click("edit-alert:0");
    assert(main.innerHTML.includes("AI에게 원하는 알림 설명하기"));
    await click("prompt-alert");
    assert(main.innerHTML.includes("어떤 상황에서 알림을 받고 싶은지 입력"));
    assert(!sent.some(message => message.cmd === "generate-alerts"));
    const request = "한화가 경기할 때 갱과 한타만 알려줘. 일정은 빼줘.";
    handlers.get("input")({ target: { dataset: { alertRequest: "" }, value: request } });
    subscriber({ to: "ui", state: structuredClone(state) });
    assert(main.innerHTML.includes(request));
    await click("prompt-alert");
    const generate = sent.find(message => message.cmd === "generate-alerts");
    assert.equal(generate.tabId, 11);
    assert.equal(generate.request, request);
    main.scrollTop = 180;
    await click('tab:entrust');
    assert.equal(main.scrollTop, 0, 'new page starts at the shared title baseline');
    main.scrollTop = 90;
    subscriber({ to: 'ui', state: structuredClone(state) });
    assert.equal(main.scrollTop, 90, 'background updates preserve the current scroll position');
    assert(main.innerHTML.includes('기본 설정'));
    subscriber({ to: 'ui', state: { ...state, status: '1번 탭이 닫혔습니다.' } });
    assert(!main.innerHTML.includes('1번 탭이 닫혔습니다.'));
    assert(!main.innerHTML.includes('id="notice" class="status"'));

    assert.equal(toggle.hidden, true);
    await click('tab:sound');
    assert.equal(toggle.hidden, false);
    assert.equal(toggle.textContent, '세부설정');
    await click('toggle-settings');
    assert.equal(toggle.hidden, true);
    assert(!main.innerHTML.includes('감지 민감도'));
    assert(main.innerHTML.includes('<h3>음량</h3>'));
    assert(main.innerHTML.includes('<h3>알림</h3>'));
    assert(main.innerHTML.includes('aria-label="사운드홈으로 돌아가기"'));
    assert(!main.innerHTML.includes('대기 소리 음소거'));
    assert(!main.innerHTML.includes('메인 소리가 나면 대기 소리 줄이기'));
    assert(!main.innerHTML.includes('AI 서버 연결'));
    await click('settings-tab:presets');
    assert.equal(main.scrollTop, 0, 'switching settings tabs resets the content position');
    assert(main.innerHTML.includes('내 프리셋'));
    await click('preset-new');
    assert(main.innerHTML.startsWith('<div class="settings-top">'));
    assert(main.innerHTML.includes('aria-label="프리셋 목록으로 돌아가기"'));
    assert(!main.innerHTML.includes('← 프리셋'));
    assert.equal(toggle.hidden, true);
    assert(main.innerHTML.includes('AI로 초안 만들기'));
    await click('draft');
    assert(main.innerHTML.includes('알림을 받고 싶은 상황을 적어주세요'));
    await click('preset-manual');
    assert(!main.innerHTML.includes('data-preset-field="summaryFocus"'));
    assert(main.innerHTML.includes('data-preset-field="keywords"'));
    handlers.get('input')({ target: { dataset: { presetField: 'name' }, value: '내 경기 알림' } });
    handlers.get('input')({ target: { dataset: { presetField: 'condition' }, value: '한타가 시작되면' } });
    subscriber({ to: 'ui', state: structuredClone(state) });
    assert(main.innerHTML.includes('한타가 시작되면'), 'state updates preserve preset draft');
    await click('save-draft');
    const savedPreset = sent.find(message => message.cmd === 'save-profile');
    assert.equal(savedPreset.profile.name, '내 경기 알림');
    assert.equal(savedPreset.profile.condition, '한타가 시작되면');
    assert(savedPreset.profile.id.startsWith('custom-'));
    assert(main.innerHTML.includes('내 프리셋'), 'saving returns to the preset list');
    assert(!main.innerHTML.includes('data-action="preset-edit"'));
    await click('preset-view:1');
    assert(main.innerHTML.startsWith('<div class="settings-top">'));
    assert(main.innerHTML.includes('aria-label="프리셋 목록으로 돌아가기"'));
    assert.equal(toggle.hidden, true);
    await click('preset-delete');
    assert(main.innerHTML.includes('<dialog class="delete-dialog"'));
    assert(main.innerHTML.includes('aria-labelledby="delete-title"'));
    assert(modalOpened > 0, 'delete opens a native modal with focus trapping');
    onCancel({ preventDefault() {} });
    assert(!main.innerHTML.includes('<dialog'), 'Escape cancels deletion');
    await click('preset-delete');
    await click('preset-delete-cancel');
    assert(!main.innerHTML.includes('<dialog'));
    assert(!sent.some(message => message.cmd === 'delete-profile'));
    await click('preset-delete');
    await click('preset-delete-confirm');
    assert(sent.some(message => message.cmd === 'delete-profile' && message.id === 'custom-game'));
    assert(main.innerHTML.includes('내 프리셋'));

    await click('tab:sound');
    await click('edit-alert:0');
    globalThis.document.activeElement = { tagName: 'TEXTAREA' };
    subscriber({ to: 'ui', state: { ...state, slots: [emptySlot(), emptySlot()], available: [{ id: 12, title: '다른 탭' }] } });
    assert(!main.innerHTML.includes('AI에게 원하는 알림 설명하기'), 'closed tab dismisses its editor even while typing');
    assert(!main.innerHTML.includes('제품 공개'), 'closed tab does not reappear as a selected source');
    assert(main.innerHTML.includes('다른 탭'), 'remaining selection stays visible');
    assert.deepEqual(savedSelections.at(-1), [null, { id: 12, title: '다른 탭' }]);
    subscriber({ to: 'ui', state: { ...state, slots: [emptySlot(), emptySlot()], available: [] } });
    assert.deepEqual(savedSelections.at(-1), [null, null]);
    assert(!main.innerHTML.includes('선택한 탭으로 이동'), 'closing a selected tab clears its stale reconnect button');
  } finally {
    globalThis.document = documentBefore;
    globalThis.chrome = chromeBefore;
  }
});
